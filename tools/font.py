def text_width(s):
    return sum(len(GLYPHS[c][0]) + 1 for c in s) - 1 if s else 0

def draw_text(put, s, x, y):
    """Calls put(px, py) for every lit pixel; y is the top of the cap height."""
    for c in s:
        g = GLYPHS[c]
        for j, row in enumerate(g):
            for i, ch in enumerate(row):
                if ch == "#":
                    put(x + i, y + j)
        x += len(g[0]) + 1
