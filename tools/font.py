"""Pixel font: 9 rows per glyph (0-6 above the baseline, 7-8 descender)."""

def _g(*rows):
    rows = list(rows) + [""] * (9 - len(rows))
    w = max(len(r) for r in rows)
    return [r.ljust(w, ".") for r in rows]

